"""
Data models for Speech Recognition (ASR), word-level timestamps, and subtitles.
"""

from typing import List, Dict, Any
from dataclasses import dataclass, field


@dataclass
class WordTiming:
    """Timestamped word token for live subtitles and audio-text synchronization."""
    word: str
    start: float
    end: float
    probability: float

    def to_dict(self) -> Dict[str, Any]:
        return {
            "word": self.word,
            "start": round(self.start, 2),
            "end": round(self.end, 2),
            "probability": round(self.probability, 4)
        }


@dataclass
class TranscriptionSegment:
    """Detailed segment generated by the ASR decoder."""
    id: int
    start: float
    end: float
    text: str
    words: List[WordTiming] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "start": round(self.start, 2),
            "end": round(self.end, 2),
            "text": self.text,
            "words": [w.to_dict() for w in self.words]
        }


@dataclass
class TranscriptionResult:
    """Comprehensive output of the Multilingual Speech-to-Text engine."""
    text: str
    language: str
    language_name: str
    language_probability: float
    duration_sec: float
    latency_ms: float
    rtf: float  # Real-Time Factor: latency_sec / duration_sec (<1.0 is faster than real-time)
    segments: List[TranscriptionSegment] = field(default_factory=list)
    words: List[WordTiming] = field(default_factory=list)

    @property
    def formatted_subtitle(self) -> str:
        """Standard subtitle format [MM:SS -> MM:SS] Language: Text."""
        start_min, start_sec = divmod(int(self.duration_sec), 60)
        return f"[{self.language.upper()}] \"{self.text}\""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "text": self.text,
            "language": self.language,
            "language_name": self.language_name,
            "language_probability": round(self.language_probability, 4),
            "duration_sec": round(self.duration_sec, 2),
            "latency_ms": round(self.latency_ms, 1),
            "rtf": round(self.rtf, 3),
            "segments": [s.to_dict() for s in self.segments],
            "words": [w.to_dict() for w in self.words]
        }
